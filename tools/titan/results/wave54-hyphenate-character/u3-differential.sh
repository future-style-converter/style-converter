#!/usr/bin/env bash
# tools/titan/results/wave54-hyphenate-character/u3-differential.sh — wave 54 lane L3: the in-process STATIC extractor
# differential for U3 / U3b (PLAN §2 L3 "May run": pure node over the 1435 sources, NO gate flags — the gate-flag
# differential [W-L3] is an orchestrator window). Three variant roots under <scratch>: base = HEAD's tools/titan/*.mjs
# (+ wpt-buckets.json), u3 = base + seam-3, u3b = base + seam-3 + seam-3b; each root symlinks tools/wpt to the tree's.
# HEAD siblings isolate the run from other lanes' in-flight edits on the shared tree. Every test of
# wave53-final's 30 tests.list files is extracted by all three; fixture and refFixture JSON compared byte for byte,
# and every line-break component's height is diffed.
# Usage: u3-differential.sh <scratch-dir>   → <scratch>/u3-differential.json + a summary on stdout
set -euo pipefail
S="$1"; R="$(cd "$(dirname "$0")/../../../.." && pwd)"; H="$R/tools/titan/results/wave54-hyphenate-character"
for v in base u3 u3b; do
  rm -rf "$S/$v"; mkdir -p "$S/$v/tools/titan"; ln -s "$R/tools/wpt" "$S/$v/tools/wpt"
  for f in $(git -C "$R" ls-tree --name-only HEAD tools/titan/ | grep -E '\.(mjs|json)$'); do git -C "$R" show "HEAD:$f" > "$S/$v/$f"; done
  # The bucket index is gitignored (generated by bucket-wpt.mjs): link the tree's copy, read-only use.
  ln -s "$R/tools/titan/wpt-buckets.json" "$S/$v/tools/titan/wpt-buckets.json"
done
(cd "$S/u3" && git apply --include='tools/titan/extract-fixture.mjs' "$H/seam-3.patch")
(cd "$S/u3b" && git apply --include='tools/titan/extract-fixture.mjs' "$H/seam-3.patch" && git apply "$H/seam-3b.patch")
cat "$R"/tools/titan/runs/wave53-final/sections/*/tests.list > "$S/all-tests.txt"
cat > "$S/diff.mjs" <<JS
import fs from 'node:fs';
const tests = fs.readFileSync('$S/all-tests.txt', 'utf8').split('\n').filter(Boolean);
const V = {};
for (const v of ['base', 'u3', 'u3b']) V[v] = await import('$S/' + v + '/tools/titan/extract-fixture.mjs');
const brs = (fx) => { const out = []; const walk = (m) => { for (const [id, c] of Object.entries(m ?? {})) { if (c._role === 'line-break') out.push([id, c.properties?.height]); walk(c.children); } }; walk(fx?.components); return out; };
const rel = (t) => t;   // bucket entries keep the css/ prefix
const res = { tests: tests.length, errors: [], u3: { changed: [], refChanged: [], brs: 0 }, u3b: { changed: [], refChanged: [], brs: 0 } };
const log = console.log; console.log = () => {}; console.warn = () => {};
for (const t of tests) {
  const r = {};
  for (const v of ['base', 'u3', 'u3b']) { try { r[v] = await V[v].extractFixture(rel(t)); } catch (e) { r[v] = { err: String(e.message).slice(0, 120) }; } }
  if (r.base.err || r.u3.err || r.u3b.err) { res.errors.push({ t, base: r.base.err, u3: r.u3.err, u3b: r.u3b.err }); if (r.base.err !== r.u3.err || r.base.err !== r.u3b.err) res.errors.at(-1).DIVERGENT = true; continue; }
  const b = brs(r.base.fixture);
  for (const [cur, prev, key] of [[r.u3, r.base, 'u3'], [r.u3b, r.u3, 'u3b']]) {
    if (JSON.stringify(cur.fixture) !== JSON.stringify(prev.fixture)) {
      const pb = brs(prev.fixture), cb = brs(cur.fixture);
      const moved = cb.filter(([id, h], k) => pb[k]?.[0] !== id || pb[k]?.[1] !== h).map(([id, h]) => id + ':' + (pb.find((x) => x[0] === id)?.[1]) + '->' + h);
      res[key].brs += moved.length;
      res[key].changed.push({ t, moved, nonBrDiff: JSON.stringify(cur.fixture).length - JSON.stringify(prev.fixture).length });
    }
    if (JSON.stringify(cur.refFixture) !== JSON.stringify(prev.refFixture)) res[key].refChanged.push(t);
  }
}
console.log = log;
fs.writeFileSync('$S/u3-differential.json', JSON.stringify(res, null, 1));
console.log('tests', res.tests, 'errors', res.errors.length, 'divergent-errors', res.errors.filter((e) => e.DIVERGENT).length);
for (const k of ['u3', 'u3b']) {
  console.log(k + ': fixtures changed ' + res[k].changed.length + ', brs moved ' + res[k].brs + ', refFixtures changed ' + res[k].refChanged.length);
  for (const c of res[k].changed) console.log('   ' + c.t.padEnd(70) + ' ' + c.moved.length + ' br  ' + c.moved.join(' '));
  for (const t of res[k].refChanged) console.log('   REF ' + t);
}
JS
nice -n 19 node "$S/diff.mjs"
