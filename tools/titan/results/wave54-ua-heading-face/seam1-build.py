#!/usr/bin/env python3
# Wave 54 lane L5 (fix pass) — regenerates seam-1.patch (GO-SMALL) from HEAD's ComponentRenderer.kt and
# seam1-files/UAElementFontRuleSeamWiringTest.kt. Nothing in the shared tree is written: the edited seam copy and the
# empty-file twin live in a temp dir; `git diff --no-index` produces the hunks, whose paths are rewritten to the repo's.
# Usage: python3 tools/titan/results/wave54-ua-heading-face/seam1-build.py   (writes seam-1.patch beside this file)
import hashlib, os, subprocess, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
SEAM = 'runtimes/compose/src/main/java/com/styleconverter/runtime/core/renderer/ComponentRenderer.kt'
TEST = 'runtimes/compose/src/test/java/com/styleconverter/runtime/typography/UAElementFontRuleSeamWiringTest.kt'
git = lambda *a: subprocess.run(['git', '-C', ROOT, *a], check=True, capture_output=True).stdout
base = git('show', f'HEAD:{SEAM}')
head_sha = git('rev-parse', 'HEAD').decode().strip()
OLD = b'''        val rawProperties = com.styleconverter.runtime.lists.ListStyleUaRule.apply(
            component._tag,
            allReset.own,
            mergeInherited(allReset.own, allReset.inherited)
        )
'''
NEW = b'''        val listUaProperties = com.styleconverter.runtime.lists.ListStyleUaRule.apply(
            component._tag,
            allReset.own,
            mergeInherited(allReset.own, allReset.inherited)
        )
        // Wave 54 (lane L5, U1-android) - the SECOND tag-keyed UA rule, twin
        // of iOS UAElementFontRule at the same cascade step for the same
        // css-cascade-4 \xc2\xa74.3 reason: `h1\xe2\x80\xa6h6 { font-size: <n>em; font-weight:
        // bold }` and `sub, sup { font-size: smaller }` (HTML \xc2\xa715.3) beat the
        // inherited body face and lose to the author's own. It runs BEFORE
        // DynamicValueResolver (below) so `em` / `ch` on the heading resolve
        // against the UA face. The heading half stands down for an element
        // that hosts child boxes (headingStandsDown - iOS's wave-40 gate,
        // verbatim). Same list instance for every untagged component (the
        // 327-pair corpus carries no `_tag`), so no committed capture moves.
        // UAElementFontRuleSeamWiringTest pins this call's exact arguments.
        val rawProperties = com.styleconverter.runtime.typography.UAElementFontRule.apply(
            component._tag,
            allReset.own,
            listUaProperties,
            standsDown = com.styleconverter.runtime.typography.UAElementFontRule.headingStandsDown(component),
        )
'''
assert base.count(OLD) == 1, 'anchor block not found exactly once at HEAD'
with tempfile.TemporaryDirectory() as tmp:
    a, b = os.path.join(tmp, 'a.kt'), os.path.join(tmp, 'b.kt')
    open(a, 'wb').write(base); open(b, 'wb').write(base.replace(OLD, NEW))
    empty = os.path.join(tmp, 'empty.kt'); open(empty, 'wb').write(b'')
    diff = lambda x, y: subprocess.run(['git', 'diff', '--no-index', '--no-color', x, y], capture_output=True).stdout.decode()
    seam_hunk = diff(a, b).replace(f'a{a}', f'a/{SEAM}').replace(f'b{b}', f'b/{SEAM}')
    test_src = os.path.join(HERE, 'seam1-files', 'UAElementFontRuleSeamWiringTest.kt')
    test_hunk = diff(empty, test_src)
# the new-file hunk: git prints the two real paths; rewrite to the repo path and the /dev/null creation form
lines = test_hunk.splitlines(keepends=True)
body = ''.join(l for l in lines if not l.startswith(('diff --git', 'index ', '--- ', '+++ ', 'new file mode', 'deleted file')))
test_hunk = (f'diff --git a/{TEST} b/{TEST}\nnew file mode 100644\n--- /dev/null\n+++ b/{TEST}\n' + body)
seam_hunk = seam_hunk.replace(f'diff --git a{a} b{b}', f'diff --git a/{SEAM} b/{SEAM}')
header = f'''# seam-1.patch - wave 54 lane L5 (ua-heading-face), revert unit U1-android - FIX PASS (GO-SMALL; regenerated by
#   tools/titan/results/wave54-ua-heading-face/seam1-build.py, never hand-edited)
# seam file: {SEAM}
# base: {head_sha} (campaign/applier-campaign HEAD at the fix pass; the seam file is byte-identical to db6e8aa0 / 7cce3b22)
# seam file sha256 at base: {hashlib.sha256(base).hexdigest()}
# anchor: :1141 `val rawProperties = com.styleconverter.runtime.lists.ListStyleUaRule.apply(` (PLAN §3 row 1),
#   before DynamicValueResolver (:1211 `.resolve(unresolvedProperties, ...)`) so `em` / `ch` resolve against the UA face
# hunks: (1) ComponentRenderer.kt - the ListStyleUaRule result hoisted into `listUaProperties`, wrapped in
#            UAElementFontRule.apply(..., standsDown = UAElementFontRule.headingStandsDown(component));
#        (2) NEW {TEST} - the source pin of (1), patch-borne so the shared tree never carries a pin red by construction
#            (rule 2b; the FloatAvoidSeamWiringTest / TableCellHugSeamWiringTest precedent).
# needs, in the SAME commit: runtimes/compose/.../typography/UAElementFontRule.kt (U1-android's new file; headingStandsDown)
# the fold-aware gate version of this patch is HELD: held/seam-1.foldgate.patch
# check: git apply --check tools/titan/results/wave54-ua-heading-face/seam-1.patch
'''
open(os.path.join(HERE, 'seam-1.patch'), 'w').write(header + seam_hunk + test_hunk)
print('wrote seam-1.patch:', hashlib.sha256((header + seam_hunk + test_hunk).encode()).hexdigest())
