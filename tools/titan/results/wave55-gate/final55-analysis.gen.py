#!/usr/bin/env python3
# tools/titan/results/wave55-gate/final55-analysis.gen.py — GENERATES final55-analysis.sh (the closing-gate read-out, PLAN §8
# step 13) from the pre-registered strings of tools/titan/results/wave55-plan/expectations.json (plan-skeptic round 1,
# process-holes S11).
#
# Why generated, at planning: wave 54 wrote final54-analysis.sh on the closing tree by copying a script, so the read-out of
# record was an unreviewed instrument — and the copy ran `python3 geometry-gate.py` (not the pinned interpreter) and read a
# prediction-terms file no wave-55 step writes. Here every command is an `expectations.json` string (scoreOfRecord,
# scoreReadout, geometryGate.closingCmd, adjudicate, …) with ONE mechanical substitution — the run ids and the record paths
# become shell variables whose DEFAULTS give the string back byte-for-byte (asserted below) — and the prediction terms are
# emitted from the prediction rows. `--check` re-renders and exits 1 when the installed script drifted from the JSON (run it
# after every regeneration, beside plan-prose.py --check).
# The script ends with ONE verdict line and exits non-zero unless R6 (the geometry gate's exit), adjudicate (R1-R5) and the
# union control all hold — so it can be proven RED on the identity record before the plan commit (readers-calibration.sh F).
# Plan-skeptic round 2 (process-holes S8): the script's FIRST command compares the sha256 of the installed expectations.json
# with the one it was generated from and exits 2 (STALE) on a mismatch — a probe-decision regeneration that forgot this
# generator can no longer run a drifted read-out (readers-calibration.sh F4).
#
# Usage: /opt/homebrew/bin/python3.12 -B tools/titan/results/wave55-gate/final55-analysis.gen.py [--check] [--exp <expectations.json>]
import hashlib, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
args = sys.argv[1:]
EXP_PATH = args[args.index('--exp') + 1] if '--exp' in args else os.path.join(ROOT, 'tools/titan/results/wave55-plan/expectations.json')
CHECK = '--check' in args
OUT = os.path.join(HERE, 'final55-analysis.sh')
E = json.load(open(EXP_PATH))
G, P = 'tools/titan/results/wave55-gate', 'tools/titan/results/wave55-plan'
BASE, CUR = E['base'], 'wave55-final'

# The substitution: run ids and record paths → variables (each default restores the pre-registered string exactly).
SUBS = [(f'{G}/score-final.movers0005.json', '"$SCORE5"'), (f'{G}/score-final.movers0.txt', '"$SCORE0_TXT"'), (f'{G}/score-final.json', '"$SCORE"'),
        (f'{G}/score-final.txt', '"$SCORE5_TXT"'), (f'{G}/geometry-final.json', '"$GEO"'), (f'{G}/geometry-final.out.txt', '"$GEO_TXT"'),
        (CUR, '"$CUR"'), (BASE, '"$PRE"')]
DEFAULTS = {'SCORE5': f'{G}/score-final.movers0005.json', 'SCORE0_TXT': f'{G}/score-final.movers0.txt', 'SCORE': f'{G}/score-final.json',
            'SCORE5_TXT': f'{G}/score-final.txt', 'GEO': f'{G}/geometry-final.json', 'GEO_TXT': f'{G}/geometry-final.out.txt', 'CUR': CUR, 'PRE': BASE}

def var(cmd):
    """The pre-registered string with the run ids / record paths as variables; asserted to round-trip under the defaults."""
    out = cmd
    for a, b in SUBS:
        out = out.replace(a, b)
    back = out
    for k, v in DEFAULTS.items():
        back = back.replace(f'"${k}"', v)
    assert back == cmd, f'the substitution does not round-trip: {cmd}'
    return out

# Prediction terms: every corpus prediction row's test path (unique), joined for cells.mjs (the rows' own terms).
terms = sorted({p['cell'].rsplit(' ', 1)[0].replace('.html', '') for l in E['lanes'].values() for p in l['predictions'] if p['kind'] != 'non-corpus'})
TERMS = '|'.join(t.split('/')[-1] for t in terms)
EXP_SHA = hashlib.sha256(open(EXP_PATH, 'rb').read()).hexdigest()

script = f"""#!/usr/bin/env bash
# tools/titan/results/wave55-gate/final55-analysis.sh — GENERATED by final55-analysis.gen.py from
# {P}/expectations.json sha256 {EXP_SHA[:16]}… — never hand-edited (`final55-analysis.gen.py --check` fails on drift).
# The wave-55 closing-gate read-out (PLAN §8 step 13): every command is a pre-registered expectations.json string with the
# run ids / record paths as variables whose defaults restore it byte-for-byte. Order: scores → geometry (R6 = its exit) →
# adjudicate (reads the --movers 0 record + the geometry JSON) → probe-readout → union control → probe→final differential →
# review sheets → red-square census → every prediction row. The LAST line is the verdict; exit 0 only when R6, adjudicate and
# the union control hold.
# Overrides (the calibration proof, readers-calibration.sh F): CUR / PRE (run ids), SCORE / GEO (an existing --movers 0 record
# / geometry JSON: the scoring / geometry step is then skipped), OUT (the read-out dir).
set -uo pipefail
cd "$(dirname "$0")/../../../.." || exit 2
EXP_SHA256="{EXP_SHA}"   # the expectations.json this script was generated from (round 2, process-holes S8)
[[ "$(shasum -a 256 {P}/expectations.json | cut -d' ' -f1)" == "$EXP_SHA256" ]] || {{ echo "STALE: final55-analysis.sh was generated from expectations.json sha256 ${{EXP_SHA256:0:16}}…; the installed one differs — re-run final55-analysis.gen.py, then --check"; exit 2; }}
CUR="${{CUR:-{CUR}}}"; PRE="${{PRE:-{BASE}}}"; OUT="${{OUT:-{G}/final}}"; mkdir -p "$OUT"
SCORE_GIVEN="${{SCORE:-}}"; GEO_GIVEN="${{GEO:-}}"
SCORE="${{SCORE:-{DEFAULTS['SCORE']}}}"; SCORE0_TXT="${{SCORE0_TXT:-{DEFAULTS['SCORE0_TXT']}}}"; SCORE5="${{SCORE5:-{DEFAULTS['SCORE5']}}}"; SCORE5_TXT="${{SCORE5_TXT:-{DEFAULTS['SCORE5_TXT']}}}"
GEO="${{GEO:-{DEFAULTS['GEO']}}}"; GEO_TXT="${{GEO_TXT:-{DEFAULTS['GEO_TXT']}}}"
echo "final55-analysis: $PRE → $CUR · records $SCORE / $GEO · out $OUT"

echo "## driver"
if [[ -d tools/titan/runs/$CUR/gate-driver ]]; then for s in tools/titan/runs/$CUR/gate-driver/*.status; do printf '%s: %s\\n' "$(basename "$s" .status)" "$(cat "$s")"; done > "$OUT/sections.status.txt"
  echo "sections OK: $(grep -c ': OK' "$OUT/sections.status.txt") / $(wc -l < "$OUT/sections.status.txt" | tr -d ' ')"; else echo "no tools/titan/runs/$CUR/gate-driver (a calibration run)"; fi

echo; echo "## scoreOfRecord (--movers 0, watchlist) — pre-registered: {E['scoreOfRecord']}"
if [[ -n "$SCORE_GIVEN" ]]; then echo "skipped: SCORE given ($SCORE)"; else
  {var(E['scoreOfRecord'])}; echo "rc=$?"; fi

echo; echo "## scoreReadout (--movers 0.005; the snapshot's source, adjudicates nothing)"
if [[ -n "$SCORE_GIVEN" ]]; then echo "skipped: SCORE given"; else
  {var(E['scoreReadout'].split('   (')[0])}; echo "rc=$?"; fi

echo; echo "## geometryGate.closingCmd — R6 is its exit (0 pass · 1 gating FAIL / self-check · 2 STALE / usage / empty scope · 3 UNMEASURED gating key)"
if [[ -n "$GEO_GIVEN" ]]; then echo "skipped: GEO given ($GEO)"; R6=0; R6=$(python3 -c "import json,sys;d=json.load(open(sys.argv[1]));print(1 if d.get('gatingFail') or d.get('selfCheckFail') else 3 if d.get('gatingUnmeasured') else 0)" "$GEO"); else
  {var(E['geometryGate']['closingCmd'])}; R6=$?; fi
echo "R6 exit $R6"

echo; echo "## adjudicate (R1-R5 + the floors + the R6 retirement read-out; exit 2 on any record that is not the base-first --movers 0 one)"
{var(E['adjudicate'])} > "$OUT/adjudicate-final.txt" 2>&1; ADJ=$?
echo "adjudicate exit $ADJ"; grep -E '^(ok|FAIL) R|ADJUDICATION|ORDER|NOT A|GEOMETRY PAIR' "$OUT/adjudicate-final.txt" | head -24 | cut -c1-180

echo; echo "## probe-readout over the closing record (rules 1-3 + leak signals over probeRun's sections; 0 expected)"
node {P}/probe-readout.mjs "$SCORE" > "$OUT/probe-readout.txt" 2>&1; echo "rc=$?"; grep -E '^summary|^PROBE|ORDER|UNKNOWN' "$OUT/probe-readout.txt" | head -4 | cut -c1-200

echo; echo "## union control (R4 / R4b with the may-move and ring-fence classes; a vanished capture or document is a leak)"
node {G}/control-check.mjs "$PRE" "$CUR" --json "$OUT/control-final-union.json" > "$OUT/control-final-union.txt" 2>&1; CTL=$?
echo "control exit $CTL"; grep -E 'withdrawn|LEAK|^total|^wire|CONTROL|REFUSED' "$OUT/control-final-union.txt" | head -12 | cut -c1-170

echo; echo "## probe → final differential (only the carriers of units reverted after wave55-probe may differ)"
if [[ -d tools/titan/runs/wave55-probe ]]; then node tools/titan/results/wave52-gate/ab-diff.mjs wave55-probe "$CUR" --threshold 0.002 > "$OUT/probe-to-final.txt" 2>&1; echo "rc=$?"; else echo "no wave55-probe run (a calibration run)"; fi

echo; echo "## review sheets (gained / lost / movers of the 0.005 record) + red-square census"
if [[ -f "$SCORE5" ]]; then for list in gained lost movers; do node tools/titan/results/wave52-gate/review-sheets.mjs "$SCORE5" $list "$PRE" "$CUR" "$OUT/sheets-$list" 2>&1 | tail -1 | cut -c1-140; done; else echo "no $SCORE5 (a calibration run)"; fi
node tools/titan/red-square-census.mjs "$CUR" > "$OUT/red-square-census.txt" 2>&1; tail -1 "$OUT/red-square-census.txt" | cut -c1-200

echo; echo "## every prediction row, open → final (terms emitted from the {len(terms)} prediction rows' tests by the generator)"
node tools/titan/results/wave52-gate/cells.mjs '{TERMS}' "$PRE" "$CUR" > "$OUT/prediction-cells.txt" 2>&1
wc -l < "$OUT/prediction-cells.txt" | xargs echo "rows:"

echo
V=HOLDS; [[ "$R6" == 0 && "$ADJ" == 0 && "$CTL" == 0 ]] || V=FAILS
echo "FINAL READ-OUT $V — R6 (geometry gate) exit $R6 · adjudicate exit $ADJ · union control exit $CTL (outputs: $OUT/)"
[[ "$V" == HOLDS ]]
"""
if CHECK:
    have = open(OUT).read() if os.path.exists(OUT) else ''
    if have != script:
        print(f'final55-analysis.sh DRIFT: it differs from its rendering of {os.path.relpath(EXP_PATH, ROOT)} — re-run final55-analysis.gen.py'); sys.exit(1)
    print(f'final55-analysis.sh in sync with expectations.json sha256 {EXP_SHA[:16]}…'); sys.exit(0)
open(OUT, 'w').write(script); os.chmod(OUT, 0o755)
print(f'wrote {os.path.relpath(OUT, ROOT)} from expectations.json sha256 {EXP_SHA[:16]}… ({len(terms)} prediction tests)')
